import 'dart:typed_data';
import 'dart:ui';

import 'package:bubblegen/bubble.dart';
import 'package:bubblegen/custom_bubble.dart';
import 'package:flutter_test/flutter_test.dart';

import 'snapshot.dart';

const _width = 40;
const _height = 32;

// Boxes are 24×16, inset by 8 from the canvas, so a nip of size 6 still fits.
final _box4 = Box.fromLTRBR(8, 8, 32, 24, 4);
final _box6 = Box.fromLTRBR(8, 8, 32, 24, 6);
final _box2468 = Box.fromLTRBAndCorners(
  8,
  8,
  32,
  24,
  topLeft: 2,
  topRight: 4,
  bottomRight: 6,
  bottomLeft: 8,
);

String _name(Object value) => value.toString().split('.').last;

List<String> _outline(CustomBubble bubble, Box box) {
  final path = Path();
  RenderBubble(bubble).createBox(path, box, null);
  return rasterize(path, _width, _height);
}

Inset _on(InsetPosType type, double from, double to) => Inset(
      InsetPos(type, Position(ratio: from)),
      InsetPos(type, Position(ratio: to)),
    );

Bubble _bubble(
  Inset inset, {
  NipAnchor anchor = NipAnchor.start,
  double offset = 0.0,
  CornerOffset cornerOffset = CornerOffset.byLength,
  double size = 6,
  double radius = 0,
}) =>
    Bubble(
      style: const BubbleStyle(),
      nip: Nip(
        inset: inset,
        size: size,
        radius: radius,
        anchor: anchor,
        offset: offset,
        cornerOffset: cornerOffset,
      ),
      topLine: const NipLine.line(0),
      bottomLine: const NipLine.line(0),
    );

void _case(String name, CustomBubble Function() bubble, Box box) {
  test(name, () {
    expectSnapshot(_snapshots, name, _outline(bubble(), box));
  });
}

const _zoom = 4.0;

/// A 10×10 window of the outline from [corner], magnified [_zoom] times, so a
/// rounded tip shows its arc.
void _tipCase(
  String name,
  CustomBubble Function() bubble,
  Box box,
  Offset corner,
) {
  test(name, () {
    final path = Path();
    RenderBubble(bubble()).createBox(path, box, null);
    final matrix = Float64List.fromList([
      _zoom, 0, 0, 0, //
      0, _zoom, 0, 0, //
      0, 0, 1, 0, //
      -corner.dx * _zoom, -corner.dy * _zoom, 0, 1, //
    ]);
    final size = (10 * _zoom).round();
    expectSnapshot(
      _snapshots,
      'rounded $name',
      rasterize(path.transform(matrix), size, size),
    );
  });
}

void main() {
  group('CustomBubble', () {
    _case('no insets, radius 4', CustomBubble.new, _box4);
    _case('no insets, radii 2 4 6 8', CustomBubble.new, _box2468);
    _case(
      'chord over bottomLeft',
      () => CustomBubble(inset: _on(InsetPosType.bottomLeft, 0, 1)),
      _box2468,
    );
    _case(
      'chords over bottomRight and bottomLeft',
      () => CustomBubble(
        insets: [
          _on(InsetPosType.bottomRight, 0, 1),
          _on(InsetPosType.bottomLeft, 0, 1),
        ],
      ),
      _box2468,
    );
    _case(
      'chord over the start of left',
      () => CustomBubble(
        inset: const Inset(
          InsetPos(InsetPosType.bottomLeft, Position(ratio: 0.5)),
          InsetPos(InsetPosType.left, Position(ratio: 0.5)),
        ),
      ),
      _box2468,
    );
    _case(
      'adjacent chords',
      () => CustomBubble(
        insets: const [
          Inset(
            InsetPos(InsetPosType.left, Position(ratio: 0.5)),
            InsetPos(InsetPosType.top, Position(ratio: 0.5)),
          ),
          Inset(
            InsetPos(InsetPosType.top, Position(ratio: 0.5)),
            InsetPos(InsetPosType.right, Position(ratio: 0.5)),
          ),
        ],
      ),
      _box4,
    );
  });

  group('Bubble on a side', () {
    for (final type in [
      InsetPosType.left,
      InsetPosType.top,
      InsetPosType.right,
      InsetPosType.bottom,
    ]) {
      final side = _on(type, 0.25, 0.75);
      _case('${_name(type)}, anchor start', () => _bubble(side), _box4);
      _case(
        '${_name(type)}, anchor end',
        () => _bubble(side, anchor: NipAnchor.end),
        _box4,
      );
      _case(
        '${_name(type)}, anchor end, offset 2',
        () => _bubble(side, anchor: NipAnchor.end, offset: 2),
        _box4,
      );
    }
  });

  group('Bubble on a corner', () {
    for (final type in [
      InsetPosType.topLeft,
      InsetPosType.topRight,
      InsetPosType.bottomRight,
      InsetPosType.bottomLeft,
    ]) {
      for (final cornerOffset in CornerOffset.values) {
        _case(
          '${_name(type)}, ${_name(cornerOffset)}',
          () => _bubble(
            _on(type, 0, 0.5),
            anchor: NipAnchor.end,
            cornerOffset: cornerOffset,
          ),
          _box6,
        );
      }
      _case(
        '${_name(type)}, byLength, offset 2',
        () => _bubble(_on(type, 0, 0.5), anchor: NipAnchor.end, offset: 2),
        _box6,
      );
    }

    _case(
      'Generator default',
      () => _bubble(
        _on(InsetPosType.topLeft, 0, 1),
        anchor: NipAnchor.end,
        cornerOffset: CornerOffset.byHeight,
      ),
      _box6,
    );

    _case(
      'left wrapping into topLeft',
      () => _bubble(
        const Inset(
          InsetPos(InsetPosType.left, Position(ratio: 0.5)),
          InsetPos(InsetPosType.left, Position(ratio: 1, offset: 3)),
        ),
        anchor: NipAnchor.end,
      ),
      _box6,
    );
  });

  group('Rounded tip', () {
    Bubble rounded(
      InsetPosType type, {
      NipAnchor anchor = NipAnchor.start,
      double offset = 0.0,
      double size = 6,
      double radius = 3,
      double from = 0.25,
      double to = 0.75,
    }) =>
        _bubble(
          _on(type, from, to),
          anchor: anchor,
          offset: offset,
          size: size,
          radius: radius,
        );

    _tipCase(
      'left, anchor start',
      () => rounded(InsetPosType.left),
      _box4,
      const Offset(0, 12),
    );
    _tipCase(
      'top, anchor start',
      () => rounded(InsetPosType.top),
      _box4,
      const Offset(12, 0),
    );
    _tipCase(
      'right, anchor start',
      () => rounded(InsetPosType.right),
      _box4,
      const Offset(30, 10),
    );
    _tipCase(
      'bottom, anchor start',
      () => rounded(InsetPosType.bottom),
      _box4,
      const Offset(18, 22),
    );
    _tipCase(
      'top, anchor end',
      () => rounded(InsetPosType.top, anchor: NipAnchor.end),
      _box4,
      const Offset(16, 0),
    );
    _tipCase(
      'top, anchor end, offset 2',
      () => rounded(InsetPosType.top, anchor: NipAnchor.end, offset: 2),
      _box4,
      const Offset(17, 0),
    );
    _tipCase(
      'top, size 2 under radius 3',
      () => rounded(InsetPosType.top, size: 2),
      _box4,
      const Offset(12, 0),
    );
    _tipCase(
      'top, size 0',
      () => rounded(InsetPosType.top, size: 0),
      _box4,
      const Offset(12, 2),
    );
    _tipCase(
      'top, size -3',
      () => rounded(InsetPosType.top, size: -3),
      _box4,
      const Offset(12, 4),
    );
    _tipCase(
      'top, size 3, offset -2',
      () => rounded(InsetPosType.top, size: 3, offset: -2),
      _box4,
      const Offset(10, 0),
    );
    _tipCase(
      'top, narrow inset under radius 6',
      () => rounded(InsetPosType.top, radius: 6, to: 0.35),
      _box4,
      const Offset(12, 0),
    );
    for (final (type, corner) in [
      (InsetPosType.topLeft, const Offset(3, 3)),
      (InsetPosType.topRight, const Offset(27, 3)),
      (InsetPosType.bottomRight, const Offset(27, 19)),
      (InsetPosType.bottomLeft, const Offset(3, 19)),
    ]) {
      _tipCase(
        '${_name(type)}, byLength',
        () => rounded(type, anchor: NipAnchor.end, from: 0, to: 0.5),
        _box6,
        corner,
      );
    }
    _tipCase(
      'Generator default',
      () => _bubble(
        _on(InsetPosType.topLeft, 0, 1),
        anchor: NipAnchor.end,
        cornerOffset: CornerOffset.byHeight,
        radius: 1.5,
      ),
      _box6,
      const Offset(0, 4),
    );
  });
}

